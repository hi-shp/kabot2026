"""Generate MCU calibration from the same JSON installed on Jetson."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
parser.add_argument('--config', type=Path, default=root / 'isv_water_trials/config/actuators.json')
parser.add_argument('--output', type=Path, default=root / 'firmware/kabot_actuator/actuator_calibration.h')
args = parser.parse_args()
cfg = json.loads(args.config.read_text(encoding='utf-8'))
lines = ['#pragma once', '// Generated by firmware/generate_config.py. Edit config/actuators.json.', 'namespace kabot_config {']
values = {'NEUTRAL_US':cfg['neutral_pwm_us'], 'MIN_US':cfg['min_pwm_us'], 'MAX_US':cfg['max_pwm_us'],
          'COMMAND_MIN_US':cfg['command_min_pwm_us'], 'COMMAND_MAX_US':cfg['command_max_pwm_us'],
          'RC_DEADBAND_US':cfg['rc_deadband_us'], 'RC_ENDPOINT_MARGIN_US':cfg['rc_endpoint_margin_us'],
          'RC_MODE_PIN':cfg['rc_mode_pin'], 'RC_HIGH_IS_MANUAL':cfg['rc_high_is_manual']}
for side in ('left', 'right'):
    for key, value in cfg[side].items():
        values[side.upper() + '_' + key.upper()] = value
for key, value in values.items():
    typ = 'bool' if type(value) is bool else 'int'
    literal = str(value).lower() if type(value) is bool else str(value)
    lines.append(f'constexpr {typ} {key} = {literal};')
lines.append('}')
data = '\n'.join(lines) + '\n'
path = args.output
if args.check:
    if not path.exists() or path.read_text(encoding='utf-8') != data:
        raise SystemExit('Firmware calibration header is stale; run firmware/generate_config.py')
else:
    path.write_text(data, encoding='utf-8')
